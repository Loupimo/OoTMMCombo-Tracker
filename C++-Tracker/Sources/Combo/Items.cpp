void ParseKey(uint8_t Key[5], ComboItem* Item)
{
    uint8_t index = 0;

    Item->GameID = Key[index];
    Item->OvType = Key[++index] & 0x7f;
    Item->SceneID = Key[++index] & 0xff;
    Item->RoomID = Key[++index] & 0xff;
    Item->ObjectID = Key[++index] & 0xff;
}

const ItemInfo * FindItem(uint32_t gi)
{
    if (gi - 1 < NUM_ITEM)
    {
        return &ItemList[gi - 1];   // -1 because the index starts at 0 while the first valid item ID starts at 1
    }

    const ItemInfo * currItem = nullptr;

    for (size_t i = 0; i < NUM_ITEM; i++)
    {
        currItem = &ItemList[i];

        if (currItem->ItemID == gi)
        {
            return currItem;
        }
    }

    return currItem;
}

// Progressive families whose upgrade tiers all share the base item's spoiler name AND whose tier
// widgets do NOT already carry the base id in their LookupKeys (so an exact match cannot list a
// base placement under the upgrade tiers). Ordered [base, first upgrade, second upgrade]; a family
// with a single upgrade (e.g. Magic Upgrade -> Double Magic) pads the unused slot with 0, which is
// never a valid item id. Per-game and shared variants are distinct families so an OoT item never
// matches an MM one; shared magic needs no entry because both magic widgets already list
// SHARED_MAGIC_UPGRADE explicitly.
static const uint32_t ProgressiveFamilies[][3] =
{
    { OOT_BOW,           OOT_QUIVER2,         OOT_QUIVER3        },
    { MM_BOW,            MM_QUIVER2,          MM_QUIVER3         },
    { SHARED_BOW,        SHARED_QUIVER2,      SHARED_QUIVER3     },
    { OOT_SLINGSHOT,     OOT_BULLET_BAG2,     OOT_BULLET_BAG3    },
    { MM_SLINGSHOT,      MM_BULLET_BAG2,      MM_BULLET_BAG3     },
    { SHARED_SLINGSHOT,  SHARED_BULLET_BAG2,  SHARED_BULLET_BAG3 },
    { OOT_MAGIC_UPGRADE, OOT_MAGIC_UPGRADE2,  0                  },
    { MM_MAGIC_UPGRADE,  MM_MAGIC_UPGRADE2,   0                  },
};

bool ItemsShareProgressiveFamily(uint32_t ItemA, uint32_t ItemB)
{
    for (const uint32_t* family : ProgressiveFamilies)
    {
        bool hasA = false;
        bool hasB = false;
        for (int i = 0; i < 3; i++)
        {
            if (family[i] == ItemA) hasA = true;
            if (family[i] == ItemB) hasB = true;
        }

        if (hasA && hasB)
        {
            return true;
        }
    }

    return false;
}

bool GetProgressiveUpgradeRequirement(uint32_t ItemID, uint32_t& OutBaseID, uint32_t& OutRequiredCount)
{
    for (const uint32_t* family : ProgressiveFamilies)
    {
        for (int pos = 1; pos < 3; pos++)
        {   // Only the upgrade tiers (index 0 is the base, not an upgrade)

            if (family[pos] == ItemID)
            {
                OutBaseID = family[0];
                OutRequiredCount = (uint32_t)(pos + 1);   // first upgrade needs 2 bases, second needs 3
                return true;
            }
        }
    }

    return false;
}

const ItemInfo* FindItemByName(QString Name)
{
    Name = Name.replace("\n", "");
    if (Name.contains("cloaked"))
    {   // Remove the cloaked part

        Name.truncate(Name.indexOf("(") - 1);   // -1 because we want to get rid of the previous space
    }

    // Match case-insensitively: some spoiler logs use inconsistent casing for the game suffix
    // (e.g. "Boomerang (OOT)" instead of "Boomerang (OoT)"), which a case-sensitive compare
    // would miss and leave untracked.
    for (size_t i = 0; i < NUM_ITEM; i++)
    {
        if (Name.compare(QString::fromUtf8(ItemList[i].ItemName), Qt::CaseInsensitive) == 0)
        {
            return &ItemList[i];
        }
    }

    // No item found: return a throwaway "Unknown" entry carrying the original name.
    size_t len = Name.length() + 1;
    char* tmpObjName = (char*)malloc(sizeof(char) * len);
    if (tmpObjName == nullptr)
    {
        return nullptr;
    }
    memcpy_s(tmpObjName, len, Name.toStdString().c_str(), len);
    tmpObjName[len - 1] = '\0';

    ItemInfo* item = new ItemInfo();
    item->ItemID = -1;
    item->ItemName = tmpObjName;
    return item;
}

// Active ROM build, read by ResolveRawItemID to translate stable-build item IDs into the
// tracker's internal (dev) numbering. Set from the spoiler "Version:" line and from the
// DLL-reported game version (see MemoryReader). Defaults to dev (identity / no shift) so dev
// builds - which already match the internal numbering - track correctly before detection runs.
static ROMVersion ActiveROMVersion = ROMVersion::dev;
static bool ActiveROMVersionFromSpoiler = false;    // true une fois qu'un spoiler "Version:" l'a fixee (fait foi).

void SetActiveROMVersion(ROMVersion Version, bool FromSpoiler)
{
    if (ActiveROMVersionFromSpoiler && !FromSpoiler)
    {   // Le spoiler fait foi : on ignore les mises a jour deduites du CRC (voir MemoryReader).

        return;
    }

    ActiveROMVersion = Version;
    if (FromSpoiler)
    {
        ActiveROMVersionFromSpoiler = true;
    }
}

bool IsActiveROMVersionFromSpoiler()
{
    return ActiveROMVersionFromSpoiler;
}

ROMVersion GetActiveROMVersion()
{
    return ActiveROMVersion;
}

uint32_t ResolveRawItemID(uint32_t RawItemID)
{
    // dev-33 reordered the OoT stick/nut upgrades: the base upgrade was pushed up to 0x80/0x81 to
    // open room for the new UPGRADE3 tier and UPGRADE2 slid down, so raw 0x77..0x7A are an explicit
    // permutation (not a step) on BOTH stable tracks. Each branch mirrors tracking.rs (rust-tracker
    // is the reference): recompose the (stable -> old-dev) table with the dev-33 renumber, then the
    // ascending steps. Tested high -> low. Dev builds already use the tracker's internal numbering.
    if (ActiveROMVersion == ROMVersion::dev)
    {
        return RawItemID;
    }

    if (ActiveROMVersion == ROMVersion::stable)
    {   // Latest stable (v31 / v32.X): the dev build has the four items the stable ROM lacks.
        // Mirror of tracking.rs RomVersion::Stable.
        if (RawItemID == 0x77) return 0x80;         // OOT_STICK_UPGRADE  (base moved up)
        if (RawItemID == 0x78) return 0x77;         // OOT_STICK_UPGRADE2 (slid down)
        if (RawItemID == 0x79) return 0x81;         // OOT_NUT_UPGRADE    (base moved up)
        if (RawItemID == 0x7A) return 0x79;         // OOT_NUT_UPGRADE2   (slid down)
        if (RawItemID >= 1024) return RawItemID + 8; // +4 (Clock/Shovel/...) + 4 (dev-33 UPGRADE3 x4)
        if (RawItemID >= 933)  return RawItemID + 7; // +3 + 4
        if (RawItemID >= 890)  return RawItemID + 6; // MM_NUT_UPGRADE region:   +2 + 4
        if (RawItemID >= 888)  return RawItemID + 5; // MM_STICK_UPGRADE region: +2 + 3
        if (RawItemID >= 509)  return RawItemID + 4; // +2 (OoT Clock/Shovel) + 2 (OoT UPGRADE3 x2)
        if (RawItemID >= 128)  return RawItemID + 2; // OoT UPGRADE3 x2 inserted at 0x78 / 0x7A

        return RawItemID;                            // < 0x77 and 0x7B..0x7F are unchanged
    }

    // v30.1: the older, larger shift, recomposed after the dev-33 renumber (same OoT stick/nut
    // reorder at the low ids). Mirror of tracking.rs RomVersion::Stable301. Tested high -> low.
    if (RawItemID == 0x77) return 0x80;             // OOT_STICK_UPGRADE
    if (RawItemID == 0x78) return 0x77;             // OOT_STICK_UPGRADE2
    if (RawItemID == 0x79) return 0x81;             // OOT_NUT_UPGRADE
    if (RawItemID == 0x7A) return 0x79;             // OOT_NUT_UPGRADE2
    if (RawItemID >= 826) return RawItemID + 114;   // MM_MASK_MAJORA (MM rusty keys)
    if (RawItemID >= 822) return RawItemID + 74;    // MM_STONE_OF_AGONY
    if (RawItemID >= 820) return RawItemID + 73;    // MM_NUT_UPGRADE
    if (RawItemID >= 818) return RawItemID + 72;    // MM_STICK_UPGRADE
    if (RawItemID >= 661) return RawItemID + 71;    // MM_SOUL_ENEMY_OCTOROK
    if (RawItemID >= 622) return RawItemID + 66;    // MM_REMAINS_ODOLWA
    if (RawItemID >= 610) return RawItemID + 58;    // MM_SONG_GORON_HALF
    if (RawItemID >= 576) return RawItemID + 50;    // MM_CHATEAU
    if (RawItemID >= 466) return RawItemID + 47;    // MM_RUPEE_GREEN (OoT rusty keys)
    if (RawItemID >= 458) return RawItemID + 18;    // OOT_TRAP_ICE
    if (RawItemID >= 452) return RawItemID + 17;    // OOT_WEIRD_MUSHROOM
    if (RawItemID >= 451) return RawItemID + 16;    // OOT_SCALE_BRONZE
    if (RawItemID >= 155) return RawItemID + 15;    // OOT_SWORD_MASTER
    if (RawItemID >= 142) return RawItemID + 9;     // OOT_SONG_NOTE_TP_FOREST
    if (RawItemID >= 128) return RawItemID + 2;     // OOT_RUPEE_RAINBOW (OoT UPGRADE3 inserts)

    return RawItemID;                               // < 0x77 and 0x7B..0x7F are unchanged
}

uint32_t ResolveRawOoTNpcID(uint32_t RawNpcID)
{
    if (ActiveROMVersion != ROMVersion::stable_30_1)
    {   // Dev builds already use the tracker's internal NPC numbering.

        return RawNpcID;
    }

    // Stable still carries the unused SCRUB_HP slot at 0x12, so the Gold Skulltula reward NPCs
    // GS_10..GS_50 are reported at 0x13..0x17 instead of the dev 0x12..0x16. Shift just that range
    // down by one. No other NPC ID moved: GS_100 only exists on dev, and every ID from
    // SHEIK_FOREST (0x18) onward is identical in both builds.
    if (RawNpcID >= 0x13 && RawNpcID <= 0x17)
    {
        return RawNpcID - 1;
    }

    return RawNpcID;
}
